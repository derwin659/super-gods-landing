export function digitsOnly(value) {
  return String(value || '').replace(/\D/g, '');
}

export function phoneCountryByIso(iso2 = 'PE') {
  return PHONE_COUNTRIES.find((country) => country.iso2 === String(iso2).toUpperCase())
    || PHONE_COUNTRIES[0];
}

function countryMatches(country, digits, requireValidLength) {
  if (!digits.startsWith(country.dial) || digits.length <= country.dial.length) return false;
  if (!requireValidLength) return true;
  const nationalLength = digits.length - country.dial.length;
  return nationalLength >= country.min && nationalLength <= country.max;
}

function detectCountry(digits, requireValidLength = false) {
  return PHONE_COUNTRIES
    .filter((country) => countryMatches(country, digits, requireValidLength))
    .sort((a, b) => b.dial.length - a.dial.length)[0] || null;
}

export function buildE164(countryOrIso, nationalValue) {
  const country = typeof countryOrIso === 'string'
    ? phoneCountryByIso(countryOrIso)
    : countryOrIso;
  const national = digitsOnly(nationalValue).slice(0, country.max);
  return national ? `+${country.dial}${national}` : '';
}

export function parsePhoneValue(value, fallbackIso = 'PE') {
  const raw = String(value || '').trim();
  let digits = digitsOnly(raw);
  const explicitInternational = raw.startsWith('+') || raw.startsWith('00');
  if (raw.startsWith('00')) digits = digits.slice(2);

  const detected = detectCountry(digits, !explicitInternational);
  const country = detected || phoneCountryByIso(fallbackIso);
  const national = detected ? digits.slice(country.dial.length) : digits;
  const isValid = national.length >= country.min && national.length <= country.max;

  return {
    country,
    national: national.slice(0, country.max),
    e164: national ? `+${country.dial}${national.slice(0, country.max)}` : '',
    isValid,
  };
}

export function normalizePhoneE164(value, fallbackIso = 'PE') {
  return parsePhoneValue(value, fallbackIso).e164;
}

export function whatsappPhoneDigits(value, fallbackIso = 'PE') {
  return digitsOnly(normalizePhoneE164(value, fallbackIso));
}
